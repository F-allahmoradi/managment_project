"""نشست ورود وب و موبایل.

توکن خام فقط یک‌بار به کلاینت برمی‌گردد. در PostgreSQL هش SHA-256
ذخیره می‌شود. جدول api_sessions اگر نباشد همین‌جا ساخته می‌شود تا
پایگاه فعلی بدون ساخت دوبارهٔ volume هم آماده شود.
"""

