CREATE TABLE IF NOT EXISTS topics (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    parent_id integer,
    code character varying(80) NOT NULL,
    name character varying(100) NOT NULL,
    level integer NOT NULL DEFAULT 1,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT topics_pkey PRIMARY KEY (id),
    CONSTRAINT topics_parent_id_fkey
        FOREIGN KEY (parent_id) REFERENCES topics(id) ON DELETE CASCADE,
    CONSTRAINT topics_code_key UNIQUE (code),
    CONSTRAINT topics_code_not_empty CHECK (btrim(code) <> ''),
    CONSTRAINT topics_name_not_empty CHECK (btrim(name) <> ''),
    CONSTRAINT topics_level_check CHECK (level >= 1)
);

COMMENT ON TABLE topics IS
    'درخت حوزه و زیرموضوع (مالی → پرداخت → تأخیر پرداخت). parent_id فقط برای ریشه خالی است.';

COMMENT ON COLUMN topics.parent_id IS
    'خالی یعنی حوزه سطح اول؛ برای زیرموضوع باید پر باشد.';

CREATE INDEX IF NOT EXISTS topics_parent_id_idx ON topics (parent_id);

