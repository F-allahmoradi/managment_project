CREATE TABLE IF NOT EXISTS text_analyses (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    source_type_id integer NOT NULL,
    source_id integer NOT NULL,
    model character varying(120) NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT text_analyses_pkey PRIMARY KEY (id),
    CONSTRAINT text_analyses_source_type_id_fkey
        FOREIGN KEY (source_type_id) REFERENCES analysis_source_types(id) ON DELETE RESTRICT,
    CONSTRAINT text_analyses_created_by_user_id_fkey
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT text_analyses_source_id_check CHECK (source_id > 0),
    CONSTRAINT text_analyses_model_not_empty CHECK (btrim(model) <> '')
);

COMMENT ON TABLE text_analyses IS
    'یک بار اجرای NLP روی متن خام ذخیره‌شده. منبع با source_type + source_id مشخص می‌شود؛ متن در جدول عملیاتی می‌ماند.';

CREATE INDEX IF NOT EXISTS text_analyses_source_idx
    ON text_analyses (source_type_id, source_id, created_at DESC);
CREATE INDEX IF NOT EXISTS text_analyses_created_by_idx
    ON text_analyses (created_by_user_id, created_at DESC);

