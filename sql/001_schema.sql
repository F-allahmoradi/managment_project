CREATE OR REPLACE FUNCTION contents_validate_kind()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_code character varying(20);
BEGIN
    SELECT code INTO v_code
    FROM content_kinds
    WHERE id = NEW.content_kind_id;

    IF v_code = 'TEXT' THEN
        IF btrim(coalesce(NEW.text_body, '')) = '' THEN
            RAISE EXCEPTION 'TEXT content requires text_body';
        END IF;
        IF NEW.media_file_id IS NOT NULL THEN
            RAISE EXCEPTION 'TEXT content must not have media_file_id';
        END IF;
    ELSIF v_code IN ('VOICE', 'IMAGE', 'FILE') THEN
        IF NEW.media_file_id IS NULL THEN
            RAISE EXCEPTION '% content requires media_file_id', v_code;
        END IF;
    ELSE
        RAISE EXCEPTION 'Unknown content kind code: %', v_code;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER contents_validate_kind_trg
    BEFORE INSERT OR UPDATE ON contents
    FOR EACH ROW
    EXECUTE FUNCTION contents_validate_kind();

